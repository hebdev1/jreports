import { useState, type CSSProperties } from 'react';
import manifest from '../generated/images.json';

type Meta = { w: number; h: number; widths: number[] };
const IMAGES = manifest as Record<string, Meta>;

interface ImgProps {
  /** File name inside public/assets, e.g. `james-emmy.png`. */
  src: string;
  alt: string;
  /** CSS object-position; carries the crops saved in the design's image slots. */
  position?: string;
  sizes?: string;
  eager?: boolean;
  /** `fill` (default) stretches to the positioned parent, like the design's <image-slot>. */
  layout?: 'fill' | 'block';
  style?: CSSProperties;
}

/**
 * Standalone replacement for the design tool's <image-slot>: a responsive
 * WebP <picture> (generated by `npm run images`) with the original file as
 * fallback. A missing or broken image leaves the frame's background colour
 * and the alt text instead of a broken-image icon.
 */
export function Img({ src, alt, position = '50% 50%', sizes = '100vw', eager = false, layout = 'fill', style }: Readonly<ImgProps>) {
  const [failed, setFailed] = useState(false);
  const meta = IMAGES[src];
  const base = src.replace(/\.[a-z]+$/i, '');
  const fill: CSSProperties = layout === 'fill' ? { position: 'absolute', inset: 0, width: '100%', height: '100%' } : { width: '100%', height: 'auto' };

  if (failed) {
    return (
      <div role="img" aria-label={alt} style={{ ...fill, display: 'grid', placeItems: 'center', padding: 16, textAlign: 'center', fontSize: 13, color: '#8E9AC0', ...style }}>
        <span aria-hidden="true">{alt}</span>
      </div>
    );
  }

  return (
    <picture>
      {meta && <source type="image/webp" sizes={sizes} srcSet={meta.widths.map((w) => `/assets/opt/${base}-${w}.webp ${w}w`).join(', ')} />}
      <img
        src={`/assets/${src}`}
        alt={alt}
        width={meta?.w}
        height={meta?.h}
        loading={eager ? 'eager' : 'lazy'}
        decoding="async"
        fetchPriority={eager ? 'high' : undefined}
        onError={() => setFailed(true)}
        style={{ ...fill, objectFit: 'cover', objectPosition: position, display: 'block', ...style }}
      />
    </picture>
  );
}
